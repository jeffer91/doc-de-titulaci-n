'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const env={window:{},Date,Math};
vm.createContext(env);
vm.runInContext(fs.readFileSync(path.join(__dirname,'../renderer/antiplagio.model.js'),'utf8'),env);
const M=env.window.UTET_ANTIPLAGIO_MODEL;
assert.equal(M.SOURCE_TYPES.length,7);
assert.ok(M.SOURCE_TYPES.some(x=>x.key==='institucional'));
assert.equal(M.periodDate('2025-10__2026-03'),'2026-04-15');
assert.equal(M.periodDate('2026-04__2026-09'),'2026-10-15');
assert.equal(M.periodDate('2026-05__2026-10'),'2026-11-16');
assert.equal(M.normalizeCareer('Gestión de Talento Humano Online','').carrera,'Gestión de Talento Humano');
assert.equal(M.normalizeCareer('Online Contabilidad','').modalidad,'En línea');
assert.equal(M.normalizeCareer('CONTABILIDAD','').modalidad,'No registrada');
assert.equal(M.number('19.99'),19.99);
const date='2026-04-15',id='2025-10__2026-03__0102030405';
const sample=M.example(id);
assert.equal(sample.similitud,M.example(id).similitud);
assert.equal(sample.origen,'simulado');
assert.equal(Object.keys(sample.fuentes).length,7);
assert.ok(Number(sample.similitud)<20);
const row={...M.createRow({estudianteId:id,cedula:'0102030405',nombres:'Ejemplo académico',carreraId:'C01',carreraNombre:'ADMINISTRACIÓN ONLINE'}),...sample,
  fecha:date,modalidad:'',sede:'Matriz',jornada:'Nocturna',referencia:'UTET-ANT-2026-04-0001',folio:'01 MEM-ITSQMET-UTET-2026-04-15'};
const html=M.individualHTML(row,{},'Octubre 2025 – Marzo 2026');
assert.ok(html.includes('RESULTADO DEL ANÁLISIS DE SIMILITUD DEL TRABAJO DE TITULACIÓN'));
assert.ok(html.includes('Repositorio institucional ITSQMET'));
assert.ok(html.includes('Modalidad de estudios'));
assert.ok(html.includes('En línea'));
assert.ok(html.includes('COORDINADOR DE TITULACIÓN'));
assert.ok(!html.includes('DATOS ILUSTRATIVOS · NO CONSTITUYEN UN ANÁLISIS REAL'));
assert.ok(!html.includes('ap-simulation'),'No se admite marca de agua diagonal en ninguna página');
assert.ok(!html.includes('ap-sample-note'),'No se agregan notas de demostración al PDF');
assert.ok(!html.includes('Datos de demostración:'));
assert.ok(!html.includes('SIMULACIÓN'));
assert.ok(html.includes('Contexto del análisis.'));
assert.ok(html.includes('El presente anexo amplía el resultado comunicado en el memorando'));
assert.ok(html.includes('Memorando N.º <span class="ap-word-code">'));
assert.ok(html.includes('src="assets/logo-itsqmet.png"'));
assert.ok(html.includes('src="assets/memorando-pie-itsqmet.svg"'));
const firstPage=html.split('</section>')[0];
assert.ok(firstPage.includes('Por medio del presente, se notifica el resultado del análisis de similitud correspondiente a su trabajo de titulación'));
assert.ok(firstPage.includes('De acuerdo con el reporte de similitud, el trabajo presenta un índice del'));
assert.ok(firstPage.includes('inferior al límite institucional establecido del 20 %'));
assert.ok(firstPage.includes('CUMPLE CON EL CRITERIO DE SIMILITUD'));
assert.ok(firstPage.includes('no constituye, por sí mismo, una determinación de plagio ni implica la aprobación integral del trabajo de titulación'));
assert.ok(firstPage.includes('Para efectos de respaldo y seguimiento académico, se adjunta el reporte individual de similitud'));
assert.ok(!firstPage.includes('me dirijo a usted para comunicar'),'Texto anterior ya no debe aparecer');
assert.ok(firstPage.includes('ap-word-memorandum'));
assert.ok(firstPage.includes('ap-word-fields'));
assert.ok(firstPage.includes('ap-word-signature'));
assert.ok(firstPage.includes('COORDINADOR DE TITULACIÓN'));
assert.ok(!firstPage.includes('ap-personal-card'),'La primera hoja no puede contener tarjetas del anexo');
assert.ok(!firstPage.includes('ap-word-context'),'El contexto solo debe estar en el anexo');
assert.ok(!firstPage.includes('ap-sample-note'),'La portada no lleva nota de demostración');
const annex=html.split('</section>')[1];
assert.ok(annex.includes('ap-word-context'),'El contexto debe preceder a las tarjetas del anexo');
assert.ok(!annex.includes('ap-sample-note'),'El anexo tampoco debe presentar notas de demostración');
assert.ok(annex.indexOf('ap-word-context')<annex.indexOf('1. Información académica'));
assert.ok(annex.includes('1. Información académica'));
assert.ok(annex.includes('2. Resultado de similitud'));
assert.ok(annex.includes('3. Fuentes consideradas'));
assert.equal((html.match(/class="inst-page ap-page/g)||[]).length,2);
assert.ok(!html.includes('Reporte consolidado'));
const aprobadoBorde=M.individualHTML({...row,origen:'real',similitud:'19.99'}, {}, 'Octubre 2025 – Marzo 2026');
const noAprobadoBorde=M.individualHTML({...row,origen:'real',similitud:'20.00'}, {}, 'Octubre 2025 – Marzo 2026');
assert.ok(aprobadoBorde.includes('inferior al límite institucional establecido del 20 %'));
assert.ok(noAprobadoBorde.includes('igual o superior al límite institucional establecido del 20 %'));
assert.ok(!aprobadoBorde.includes('Datos de demostración'));
assert.ok(!noAprobadoBorde.includes('Datos de demostración'));
const real=M.individualHTML({...row,origen:'real',similitud:'20.00'}, {}, 'Octubre 2025 – Marzo 2026');
assert.ok(real.includes('NO APROBADO'));
assert.ok(real.includes('igual o superior al límite institucional establecido del 20 %'));
assert.ok(real.includes('NO CUMPLE CON EL CRITERIO DE SIMILITUD'));
assert.ok(real.includes('presentar nuevamente el trabajo para su análisis'));
assert.ok(real.includes('presentar nuevamente'));
assert.ok(!real.includes('DATOS ILUSTRATIVOS'));
assert.ok(!real.includes('ap-simulation'),'No se generan marcas de agua');
assert.ok(!real.includes('ap-sample-note'),'Ningún documento debe mostrar notas de demostración');
const injected=M.individualHTML({...row,nombres:'<script>alert(1)</script>'},{},'Período');
assert.ok(!injected.includes('<script>'));
assert.ok(injected.includes('&lt;script&gt;'));
const store=require('../electron/antiplagio-store.js');
assert.equal(store.code(1,date),'01 MEM-ITSQMET-UTET-2026-04-15');
assert.equal(store.key('2025-10__2026-03','0102030405'),id);
assert.equal(store.safeRecord({...row,periodoId:'2025-10__2026-03',estudianteId:id,periodoNombre:'Octubre 2025 – Marzo 2026',versionPlantilla:'2'}).origen,'simulado');
assert.throws(()=>store.safeRecord({...row,periodoId:'2025-10__2026-03',estudianteId:id,similitud:'120'}),/Porcentaje/);
console.log('OK antiplagio: memorando individual, siete fuentes, fechas, formato y validaciones.');
