'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const asset=p=>fs.readFileSync(path.join(root,'renderer','assets',p));
const png=asset('utet-app-icon.png');
const ico=asset('utet-app-icon.ico');
assert.equal(png.subarray(0,8).toString('hex'),'89504e470d0a1a0a');
assert.equal(png.readUInt32BE(16),256);
assert.equal(png.readUInt32BE(20),256);
assert.equal(ico.readUInt16LE(0),0);
assert.equal(ico.readUInt16LE(2),1);
const count=ico.readUInt16LE(4);
assert.equal(count,5,'El icono Windows necesita cinco tamaños.');
const sizes=[],entries=[];
for(let i=0;i<count;i++){
 const start=6+i*16;
 const width=ico[start]||256,height=ico[start+1]||256;
 const length=ico.readUInt32LE(start+8),offset=ico.readUInt32LE(start+12);
 assert.equal(width,height);
 assert.ok(offset+length<=ico.length,'La imagen del ICO debe estar dentro del archivo.');
 assert.equal(ico.subarray(offset,offset+8).toString('hex'),'89504e470d0a1a0a');
 sizes.push(width);entries.push({width,length});
}
assert.deepEqual(sizes,[16,32,48,64,256]);
const main=fs.readFileSync(path.join(root,'electron','main.js'),'utf8');
const html=fs.readFileSync(path.join(root,'renderer','index.html'),'utf8');
const css=fs.readFileSync(path.join(root,'renderer','minimal.css'),'utf8');
const pkg=require('../package.json');
assert.match(main,/icon:\s*WINDOW_ICON/);
assert.match(main,/setAppUserModelId/);
assert.match(html,/rel="icon" href="assets\/utet-app-icon\.ico"/);
assert.match(html,/rel="apple-touch-icon"/);
assert.match(html,/class="identity-logo"/);
assert.match(css,/\.identity-logo/);
assert.equal(pkg.build.win.icon,'renderer/assets/utet-app-icon.ico');
assert.equal(pkg.build.nsis.createDesktopShortcut,true);
assert.equal(pkg.build.nsis.createStartMenuShortcut,true);
console.log('OK branding UTET: PNG 256, ICO 16/32/48/64/256, favicon, ventana, barra de tareas y accesos directos.');
