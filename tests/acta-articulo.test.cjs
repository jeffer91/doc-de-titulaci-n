'use strict';
const assert=require('node:assert/strict');
const Dates=require('../electron/acta-articulo-date.js');
const E=require('../electron/acta-articulo-evidence.js');
const A=require('../renderer/acta-articulo.model.js');
const Store=require('../electron/acta-articulo.js');
const p='2025-10__2026-03',cedula='0105483465';
const due=Dates.forPeriod(p);
assert.equal(due.date,'2026-05-29');
assert.equal(due.documentCode,'AT-ITSQMET-UTET-2026-05');
assert.equal(due.calendarVerified,true);
assert.equal(Dates.forPeriod('2026-04__2026-09').date,'2026-11-30');
assert.equal(Dates.forPeriod('2026-05__2026-10').date,'2026-12-31');
assert.equal(Dates.forPeriod(p,['2026-05-29']).date,'2026-05-28');
assert.equal(Dates.allowed(p,new Date('2026-05-25T13:00:00Z')).ready,false);
assert.equal(Dates.allowed(p,new Date('2026-05-30T13:00:00Z')).ready,true);
assert.throws(()=>Dates.forPeriod('2025-13__2026-03'),/fuera de rango/);
assert.equal(Store.numberCode(due,cedula,1),'AA-2026-0105-05-0001');
assert.equal(Store.numberCode(due,cedula,129),'AA-2026-0105-05-0129');
const reqValues=Object.fromEntries([...E.REQS,...E.APPROVALS].map(([k])=>[k,'CUMPLE']));
const requirements={periodoId:p,cedula,valores:reqValues};
const notas={periodoId:p,cedula,notaArticulo:7,notaDefensa:7,modalidadTitulacion:'ARTICULO_ACADEMICO'};
const matricula={periodoId:p,cedula,modalidadTitulacion:'ARTICULO_ACADEMICO'};
const plagio={periodoId:p,cedula,similitud:'20.00',origen:'real'};
const make=(overrides={})=>E.assess({requisitos:requirements,notas,matricula,antiplagio:plagio,periodoId:p,cedula,...overrides});
let check=make();
assert.equal(check.eligible,true,'20.00% es el máximo inclusivo');
assert.equal(check.requirements.length,9);
assert.equal(check.approvals.length,2);
assert.equal(check.checks.articulo,'CUMPLE');
assert.equal(check.checks.defensa,'CUMPLE');
assert.equal(make({antiplagio:{...plagio,similitud:'20.01'}}).eligible,false);
assert.equal(make({antiplagio:{...plagio,origen:'simulado'}}).eligible,false);
assert.equal(make({notas:{...notas,notaArticulo:6.99}}).eligible,false);
assert.equal(make({notas:{...notas,notaDefensa:6.99}}).eligible,false);
assert.equal(make({requisitos:{...requirements,valores:{...reqValues,Ingles:'PENDIENTE'}}}).eligible,false);
assert.equal(make({notas:null}).eligible,false);
assert.equal(make({matricula:null}).eligible,false);
assert.equal(make({matricula:{...matricula,estadoMatricula:'RETIRADO'}}).eligible,false);
assert.equal(make({matricula:{...matricula,modalidadTitulacion:'EXAMEN_COMPLEXIVO'},notas:{...notas,modalidadTitulacion:''}}).eligible,false);
const sample={
 modalidad:'ARTICULO_ACADEMICO',periodoId:p,cedula,numeroActa:'AA-2026-0105-05-0129',
 codigoDocumento:due.documentCode,fechaEmision:due.date,fechaRegistro:'2026-11-07',
 nombre:'ESTUDIANTE DE REFERENCIA',carrera:'DESARROLLO DE SOFTWARE',modalidadEstudios:'En línea',
 requisitos:check.requirements,aprobaciones:check.approvals,comprobaciones:check.checks
};
assert.equal(A.valid(sample),true);
const html=A.render(sample,'Octubre 2025 a Marzo 2026');
assert.equal((html.match(/class="aa-page /g)||[]).length,3);
assert.ok(html.includes('Acta de Titulación por Artículo Académico'));
assert.ok(html.includes('ELABORADO'));
const fs=require('node:fs');
const path=require('node:path');
const css=fs.readFileSync(path.join(__dirname,'../renderer/acta-articulo.css'),'utf8');
assert.match(css,/\.aa-signatures th\{font-weight:700;border-bottom:0\}/);
assert.match(css,/\.aa-signatures tbody \.aa-signature-space td\{border-top:0\}/);
assert.match(css,/\.aa-signatures th,\.aa-signatures td\{border:1px solid/,'Mantener restantes bordes de firmas');
assert.ok(html.includes('MSc. Jefferson Villarreal'));
assert.ok(html.includes('Ing. Martha Tomalá'));
assert.ok(html.includes('Dr. Alex León T.'));
assert.ok(html.includes('N.º DE ACTA: AA-2026-0105-05-0129'));
assert.ok(html.includes('Aprobación del artículo académico'));
assert.ok(html.includes('Artículo académico · mínimo 7/10 acreditado'));
assert.ok(html.includes('Similitud · máximo 20,00 % acreditado'));
assert.ok(!html.includes('notaArticulo'));
assert.ok(!html.includes('7,00'),'La calificación numérica del estudiante no se imprime');
assert.ok(html.includes('Página 3 de 3'));
assert.ok(html.includes('AT-ITSQMET-UTET-2026-05'));
assert.throws(()=>A.render({...sample,aprobaciones:[{label:'Aprobación',status:'PENDIENTE'}]},'Período'),/no se puede generar/i);
assert.ok(!A.valid({...sample,comprobaciones:{...check.checks,similitud:'NO CUMPLE'}}));
assert.equal(A.filename(sample),'ACTA_AA_0105483465_AA-2026-0105-05-0129.pdf');
// ---- Examen Complexivo (PRO-93): misma plantilla, prefijo CX, sin notas ni similitud. ----
const Mod=require('../renderer/acta-titulacion.modalidades.js');
assert.deepEqual(Mod.IDS,['ARTICULO_ACADEMICO','TRABAJO_TITULACION','EXAMEN_COMPLEXIVO']);
assert.equal(Mod.fromDoc('acta-examen').prefix,'CX');
assert.equal(Mod.fromDoc('acta-trabajo').prefix,'TT');
assert.equal(Mod.fromDoc('plagio-trabajo'),null);
assert.throws(()=>Mod.get('OTRA'),/no reconocida/);
assert.equal(Store.numberCode(due,'0106832819',9,'EXAMEN_COMPLEXIVO'),'CX-2026-0106-05-0009');
assert.equal(Store.numberCode(due,cedula,284,'TRABAJO_TITULACION'),'TT-2026-0105-05-0284');
assert.equal(Store.registryId(Mod.get('EXAMEN_COMPLEXIVO'),p+'__'+cedula),'CX__'+p+'__'+cedula);
const cxMatricula={periodoId:p,cedula,modalidadTitulacion:'EXAMEN_COMPLEXIVO'};
const cx=E.assess({requisitos:requirements,notas:null,matricula:cxMatricula,antiplagio:null,periodoId:p,cedula,modalidad:'EXAMEN_COMPLEXIVO'});
assert.equal(cx.eligible,true,'Complexivo no exige ficha de notas ni memorando de similitud');
assert.deepEqual(Object.keys(cx.checks),['modalidad']);
assert.equal(cx.approvals[1].label,'Aprobación complexivo/proyecto');
assert.equal(E.assess({requisitos:requirements,notas:null,matricula:{...cxMatricula,modalidadTitulacion:''},antiplagio:null,periodoId:p,cedula,modalidad:'EXAMEN_COMPLEXIVO'}).eligible,false,'Sin modalidad registrada no hay acta');
assert.equal(E.assess({requisitos:requirements,notas:{periodoId:p,cedula,modalidadTitulacion:'EXAMEN_COMPLEXIVO'},matricula:{...cxMatricula,modalidadTitulacion:''},antiplagio:null,periodoId:p,cedula,modalidad:'EXAMEN_COMPLEXIVO'}).eligible,true,'La modalidad puede venir de la ficha de notas');
assert.equal(E.assess({requisitos:requirements,notas:null,matricula:matricula,antiplagio:null,periodoId:p,cedula,modalidad:'EXAMEN_COMPLEXIVO'}).eligible,false,'Un estudiante de Artículo no recibe acta CX');
assert.equal(E.assess({requisitos:{...requirements,valores:{...reqValues,AprobacionComplexivoProyecto:'NO CUMPLE'}},notas:null,matricula:cxMatricula,antiplagio:null,periodoId:p,cedula,modalidad:'EXAMEN_COMPLEXIVO'}).eligible,false);
const cxSample={...sample,modalidad:'EXAMEN_COMPLEXIVO',cedula:'0106832819',numeroActa:'CX-2026-0106-05-0009',carrera:'CONTABILIDAD',
 requisitos:cx.requirements,aprobaciones:cx.approvals,comprobaciones:cx.checks};
assert.equal(A.valid(cxSample),true);
assert.equal(A.valid({...cxSample,numeroActa:'AA-2026-0106-05-0009'}),false,'El número debe llevar el prefijo de su modalidad');
assert.equal(A.valid({...sample,numeroActa:'CX-2026-0105-05-0129'}),false);
const cxHtml=A.render(cxSample,'Octubre 2025 a Marzo 2026');
assert.equal((cxHtml.match(/class="aa-page /g)||[]).length,3);
assert.ok(cxHtml.includes('Acta de Titulación por Examen<br>Complexivo'));
assert.equal((cxHtml.match(/Acta de Titulación por Examen Complexivo/g)||[]).length,3,'Encabezado en las tres hojas');
assert.ok(cxHtml.includes('N.º DE ACTA: CX-2026-0106-05-0009'));
assert.ok(cxHtml.includes('Modalidad de titulación</th><td>Examen Complexivo'));
assert.ok(cxHtml.includes('se administran exclusivamente en Ncomplex'));
assert.ok(cxHtml.includes('4. Aprobaciones institucionales'));
assert.ok(cxHtml.includes('5. Constancia documental'),'Complexivo no tiene sección de condiciones académicas');
assert.ok(!cxHtml.includes('Verificación de las condiciones académicas'));
assert.ok(!cxHtml.includes('Artículo'));
assert.ok(cxHtml.includes('La presente acta registra el cumplimiento de los nueve requisitos'));
assert.ok(!cxHtml.includes('Firmado electrónicamente'),'No se simulan sellos de firma electrónica');
assert.equal(A.filename(cxSample),'ACTA_COMPLEX_0106832819_CX-2026-0106-05-0009.pdf');
// ---- Trabajo de Titulación (PRO-164): notas de trabajo escrito y defensa, similitud del memorando de trabajo. ----
const ttNotas={periodoId:p,cedula,notaEscrito:8.5,notaDefensa:7,modalidadTitulacion:'TRABAJO_TITULACION'};
const ttMake=(o={})=>E.assess({requisitos:requirements,notas:ttNotas,matricula:{periodoId:p,cedula,modalidadTitulacion:'TRABAJO_TITULACION'},antiplagio:{...plagio,similitud:'19.99'},periodoId:p,cedula,modalidad:'TRABAJO_TITULACION',...o});
const tt=ttMake();
assert.equal(tt.eligible,true);
assert.deepEqual(Object.keys(tt.checks),['trabajo','defensa','similitud','modalidad']);
assert.equal(tt.approvals[1].label,'Aprobación del trabajo de titulación');
assert.equal(ttMake({notas:{...ttNotas,notaEscrito:6.9}}).eligible,false);
assert.equal(ttMake({notas:{...ttNotas,notaEscrito:null,notaArticulo:9}}).eligible,false,'La nota de artículo no sustituye la del trabajo');
assert.equal(ttMake({antiplagio:{...plagio,similitud:'20.5'}}).eligible,false);
assert.equal(ttMake({antiplagio:{...plagio,similitud:'20.00'}}).eligible,false);
assert.equal(ttMake({antiplagio:null}).eligible,false);
assert.equal(ttMake({notas:{...ttNotas,modalidadTitulacion:'ARTICULO_ACADEMICO'}}).eligible,false);
const ttSample={...sample,modalidad:'TRABAJO_TITULACION',numeroActa:'TT-2026-0105-05-0001',requisitos:tt.requirements,aprobaciones:tt.approvals,comprobaciones:tt.checks};
assert.equal(A.valid(ttSample),true);
const ttHtml=A.render(ttSample,'Octubre 2025 a Marzo 2026');
assert.ok(ttHtml.includes('Acta de Titulación por Trabajo de<br>Titulación'));
assert.ok(ttHtml.includes('Trabajo de titulación · mínimo 7/10 acreditado'));
assert.ok(ttHtml.includes('5. Verificación de las condiciones académicas'));
assert.ok(ttHtml.includes('6. Constancia documental'));
assert.ok(!ttHtml.includes('8,5')&&!ttHtml.includes('8.5'),'Sin calificaciones impresas');
assert.equal(A.filename(ttSample),'ACTA_TT_0105483465_TT-2026-0105-05-0001.pdf');
assert.ok(!A.valid({...ttSample,comprobaciones:{...tt.checks,trabajo:'NO CUMPLE'}}));
